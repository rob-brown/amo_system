  @sram Map.new(@machines, fn {name, hex} -> {name, Base.decode16!(hex, case: :lower)} end)

  def names do
    @sram |> Map.keys() |> Enum.sort()
  end

  def sram(name) when is_atom(name) do
    Map.fetch(@sram, name)
  end

  def name(<<_::binary-size(64)>> = sram) do
    Enum.find_value(@sram, fn
      {name, ^sram} -> name
      _ -> nil
    end)
  end
end
